def cn_of(topic):
    """topic -> 中文名；未收录时返回 None"""
    hit = T.get(topic.lower())
    return hit[0] if hit else None


def cat_of(topic):
    hit = T.get(topic.lower())
    return hit[1] if hit else None


def dump_js(path):
    """导出前端用的 topic 中文词典"""
    import json
    payload = {k: v[0] for k, v in T.items()}
    body = json.dumps(payload, ensure_ascii=False, separators=(',', ':'))
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write('/* topic 中文词典 —— 由 _build/topics.py 生成，请勿手改 */\n')
        f.write('window.GH_TOPICS = ')
        f.write(body)
        f.write(';\n')
    return len(payload)


